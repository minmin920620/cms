    /**
     * Get boundaries for a specific barangay by slug.
     */
    public static function get(string $slug): ?array
    {
        $all = static::all();

        return $all[$slug] ?? null;
    }

    /**
     * Get all boundary polygons as a GeoJSON FeatureCollection.
     */
    public static function toGeoJson(): array
    {
        $features = [];

        foreach (static::all() as $slug => $barangay) {
            $features[] = [
                'type' => 'Feature',
                'geometry' => [
                    'type' => 'Polygon',
                    'coordinates' => [$barangay['coordinates']],
                ],
                'properties' => [
                    'slug' => $slug,
                    'name' => 'Brgy. ' . $barangay['name'],
                    'barangay' => 'Brgy. ' . $barangay['name'],
                    'source' => 'Predefined polygon boundary',
                ],
            ];
        }

        return [
            'type' => 'FeatureCollection',
            'features' => $features,
        ];
    }
